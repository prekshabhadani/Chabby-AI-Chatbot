import json
import os
from datetime import datetime, timezone
from uuid import UUID

import streamlit as st
from cryptography.fernet import Fernet, InvalidToken
from supabase import create_client


def _setting(name: str) -> str:
    value = os.getenv(name, "").strip()
    if not value:
        try:
            value = str(st.secrets.get(name, "")).strip()
        except Exception:
            value = ""
    return value


def get_supabase_client():
    """Return the authenticated Supabase client stored for this Streamlit session."""
    client = st.session_state.get("_chabby_supabase_client")
    if client is not None:
        return client

    url = _setting("SUPABASE_URL")
    key = _setting("SUPABASE_KEY")
    if not url or not key:
        raise RuntimeError(
            "Missing SUPABASE_URL or SUPABASE_KEY. Add both to your local .env "
            "and Streamlit Community Cloud Secrets."
        )

    client = create_client(url, key)
    st.session_state["_chabby_supabase_client"] = client
    return client


def get_fernet() -> Fernet:
    key = _setting("CHABBY_ENCRYPTION_KEY")
    if not key:
        raise RuntimeError("Missing CHABBY_ENCRYPTION_KEY in your environment or Streamlit Secrets.")
    try:
        return Fernet(key.encode("utf-8"))
    except Exception as exc:
        raise RuntimeError(
            "CHABBY_ENCRYPTION_KEY is invalid. Use the complete key generated by Fernet in CMD."
        ) from exc


def sign_up(email: str, password: str):
    client = get_supabase_client()
    return client.auth.sign_up({"email": email.strip(), "password": password})


def sign_in(email: str, password: str):
    client = get_supabase_client()
    response = client.auth.sign_in_with_password(
        {"email": email.strip(), "password": password}
    )
    if not response or not response.user:
        raise RuntimeError("Supabase did not return a user. Please check your login details.")
    st.session_state["chabby_user_id"] = str(response.user.id)
    st.session_state["chabby_user_email"] = response.user.email or email.strip()
    return response


def sign_out():
    client = st.session_state.get("_chabby_supabase_client")
    if client is not None:
        try:
            client.auth.sign_out()
        except Exception:
            pass

    # Remove private chat and authentication state from this browser session.
    keys_to_clear = [
        "_chabby_supabase_client",
        "chabby_user_id",
        "chabby_user_email",
        "chats",
        "active_chat_id",
        "messages",
        "vector_store",
        "pdf_signature",
        "pdf_names",
        "pdf_sources",
        "pending_prompt",
        "pdf_uploads",
        "image_uploads",
    ]
    for key in keys_to_clear:
        st.session_state.pop(key, None)


def current_user_id():
    return st.session_state.get("chabby_user_id")


def _encrypt_payload(payload: dict) -> str:
    raw = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    return get_fernet().encrypt(raw).decode("ascii")


def _decrypt_payload(encrypted_payload: str) -> dict:
    try:
        raw = get_fernet().decrypt(encrypted_payload.encode("ascii"))
        result = json.loads(raw.decode("utf-8"))
        if not isinstance(result, dict):
            raise ValueError("Chat payload is not an object.")
        return result
    except (InvalidToken, ValueError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RuntimeError(
            "A saved chat could not be decrypted. Check that CHABBY_ENCRYPTION_KEY "
            "is exactly the same key used when that chat was saved."
        ) from exc


def load_user_chats() -> dict:
    user_id = current_user_id()
    if not user_id:
        raise RuntimeError("Please log in before loading chats.")

    response = (
        get_supabase_client()
        .table("chabby_chats")
        .select("id,title,encrypted_payload,created_at,updated_at")
        .eq("user_id", user_id)
        .order("updated_at", desc=True)
        .execute()
    )

    chats = {}
    for row in response.data or []:
        payload = _decrypt_payload(row["encrypted_payload"])
        chat_id = str(row["id"])
        chats[chat_id] = {
            "title": row.get("title") or payload.get("title") or "New chat",
            "created": payload.get("created") or row.get("created_at") or "",
            "messages": payload.get("messages", []),
        }
    return chats


def save_user_chat(chat_id: str, chat: dict):
    user_id = current_user_id()
    if not user_id:
        raise RuntimeError("Please log in before saving chats.")

    # The table uses a PostgreSQL UUID column, so chat IDs must be UUIDs.
    try:
        normalized_id = str(UUID(str(chat_id)))
    except (ValueError, TypeError, AttributeError) as exc:
        raise RuntimeError("Invalid chat ID. Start a new chat and try again.") from exc

    payload = {
        "title": chat.get("title", "New chat"),
        "created": chat.get("created") or datetime.now(timezone.utc).isoformat(),
        "messages": chat.get("messages", []),
    }
    now = datetime.now(timezone.utc).isoformat()
    row = {
        "id": normalized_id,
        "user_id": user_id,
        "title": payload["title"],
        "encrypted_payload": _encrypt_payload(payload),
        "updated_at": now,
    }

    # RLS checks that the authenticated user owns this row.
    get_supabase_client().table("chabby_chats").upsert(row, on_conflict="id").execute()


def delete_user_chat(chat_id: str):
    user_id = current_user_id()
    if not user_id:
        raise RuntimeError("Please log in before deleting chats.")
    get_supabase_client().table("chabby_chats").delete().eq(
        "id", str(chat_id)
    ).eq("user_id", user_id).execute()
